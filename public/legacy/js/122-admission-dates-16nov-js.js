  /* Format a Date object as "D Mon YYYY" */
  function fmt(d){
    return d.getDate() + ' ' + d.toLocaleString('en-GB',{month:'short'}) + ' ' + d.getFullYear();
  }

  /* Compute admission date as today minus p.day days */
  function dateFromDay(day){
    var d = new Date();
    d.setDate(d.getDate() - Math.max(0, parseInt(day,10)||0));
    return fmt(d);
  }

  /* Inject style once */
  function ensureStyle(){
    if(document.getElementById('tagadm-css')) return;
    var s = document.createElement('style');
    s.id = 'tagadm-css';
    s.textContent = '.tagadm{display:inline-block;background:#e8f4ff;color:#0056b3;'
      + 'border:1px solid #b3d4f5;border-radius:4px;padding:1px 7px;'
      + 'font-size:11px;font-weight:600;letter-spacing:.03em;white-space:nowrap}';
    document.head.appendChild(s);
  }

  /* Replace each .tagnew badge with the actual admission date */
  function patch(){
    ensureStyle();
    document.querySelectorAll('.tagnew').forEach(function(tag){
      var tr = tag.closest('tr');
      if(!tr) return;
      /* UHID is in the title attr of the UHID span: title="UHID 2026-27RG6812" */
      var uhidEl = tr.querySelector('[title^="UHID "]');
      var uhid = uhidEl ? uhidEl.getAttribute('title').replace('UHID ','').trim() : '';
      var dates = uhid && ADM_DATES[uhid];
      var label;
      if(dates && dates.length){
        label = dates[0];
        tag.title = dates.length > 1
          ? 'Last ' + dates.length + ' visits: ' + dates.join(', ')
          : 'Admission: ' + label;
      } else {
        /* Fallback: read Day N from the row's sub-text */
        var dayEl = tr.querySelector('.tiny.muted');
        var m = dayEl && (dayEl.textContent||'').match(/Day (\d+)/);
        label = m ? dateFromDay(m[1]) : null;
        if(label) tag.title = 'Computed from day of stay';
      }
      if(label){
        tag.textContent = 'Adm ' + label;
        tag.classList.remove('tagnew');
        tag.classList.add('tagadm');
      }
    });
  }

  /* Hook into render */
