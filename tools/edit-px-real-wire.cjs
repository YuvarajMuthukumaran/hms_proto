/* One-off (16 Nov 2026): Patient Experience on real patients, step 1: load public/px/px-real.js first on every PX page and in the bundle,
   and make the demo roster (hms-patients.js) stand aside when real mode is on. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', 'public');
const TAG = '<script src="/px/px-real.js"></script>';
let n = 0;
for (const f of ['today', 'patients', 'rounds', 'calendar', 'reports', 'training', 'owner', 'setting']) {
  const p = path.join(root, 'px', f + '.html');
  let s = fs.readFileSync(p, 'utf8');
  if (s.includes('px-real.js')) continue;
  const a = '<script src="/auth-shim.js"></script>';
  if (s.split(a).length !== 2) throw new Error('auth-shim count in ' + f);
  s = s.replace(a, a + TAG);
  fs.writeFileSync(p, s); n++;
}
/* the demo roster only applies when real mode is off */
{
  const p = path.join(root, 'px', 'hms-patients.js');
  let s = fs.readFileSync(p, 'utf8');
  if (!s.includes('PX_REAL')) {
    const i = s.indexOf('window.HMS_PATIENTS=');
    if (i < 0) throw new Error('hms-patients.js shape');
    s = s.slice(0, i) + 'if(!window.PX_REAL){\n' + s.slice(i).trimEnd() + '\n}\n';
    fs.writeFileSync(p, s); n++;
  }
}
/* the generator keeps producing the same guard */
{
  const p = path.join(__dirname, 'edit-px-hms-patients.cjs');
  let s = fs.readFileSync(p, 'utf8');
  if (!s.includes("'if(!window.PX_REAL){")) {
    s = s.replace("'/* generated by tools/gen-px-patients.cjs, do not edit */\\nwindow.HMS_PATIENTS='+JSON.stringify(json)+';\\n'", "'/* generated by tools/gen-px-patients.cjs, do not edit */\\n'+'window.HMS_PATIENTS='+JSON.stringify(json)+';\\n'");
  }
}
/* the bundle: outer head and the template */
{
  const file = path.join(root, 'px-lead-prototype.html');
  const src = fs.readFileSync(file, 'utf8');
  const tag = '<script type="__bundler/template">';
  const i0 = src.indexOf(tag, 100000) + tag.length, i1 = src.indexOf('</script>', i0);
  let t = JSON.parse(src.slice(i0, i1).trim());
  const a = '<script src="/px/hms-patients.js"></script>';
  if (t.split(a).length !== 2) throw new Error('hms-patients tag count in bundle: ' + (t.split(a).length - 1));
  if (!t.includes('px-real.js')) t = t.replace(a, TAG + '\n' + a);
  let out = src.slice(0, i0) + '\n' + JSON.stringify(t).split('</').join('<' + String.fromCharCode(92) + '/') + '\n' + src.slice(i1);
  const b = '<script src="/auth-shim.js"></script>';
  if (!out.slice(0, i0).includes('px-real.js')) {
    const k = out.indexOf(b);
    if (k < 0 || k > 2000) throw new Error('outer auth-shim position');
    out = out.slice(0, k + b.length) + TAG + out.slice(k + b.length);
  }
  fs.writeFileSync(file, out); n++;
}
console.log('edited', n);
