// One-off: split the single-file portal into css / markup / ordered script files.
// Usage: node tools/split-legacy.mjs "<path to Tulasi Clinical Portal.html>"
// Scripts listed in SKIP are replaced by the React shell (login, role links, Supabase sync).
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2];
const html = fs.readFileSync(src, 'utf8');
const SKIP = new Set(['login-js', 'role-links-js', 'supa-js']);
const outJs = 'public/legacy/js';
fs.rmSync(outJs, { recursive: true, force: true });
fs.mkdirSync(outJs, { recursive: true });

const re = /<(script|style)([^>]*)>([\s\S]*?)<\/\1>/g;
let m, n = 0, css = '', first = true;
const scripts = [];
let markup = '';
let lastEnd = 0;
while ((m = re.exec(html))) {
  const [whole, tag, attrs, body] = m;
  const id = (attrs.match(/id="([^"]+)"/) || [])[1] || (tag === 'script' ? 'portal-main' : 'inline');
  if (tag === 'style') {
    css += `/* ---- ${id} ---- */\n${body}\n`;
  } else if (!SKIP.has(id)) {
    const file = `${String(++n).padStart(2, '0')}-${id}.js`;
    fs.writeFileSync(path.join(outJs, file), body);
    scripts.push({ id, file, size: body.length });
  } else {
    console.log('skipped (replaced by React):', id);
  }
  // markup that sits between the head and the first script: the app shell, modal and toast
  if (tag === 'script' && first) {
    const gap = html.slice(lastEnd, m.index);
    const i = gap.indexOf('<div class="app" id="app">');
    markup = gap.slice(i);
    first = false;
  }
  lastEnd = m.index + whole.length;
}
fs.writeFileSync('public/legacy/legacy.css', css);
fs.writeFileSync('src/legacy/markup.html', markup.trim() + '\n');
const list = scripts.map(s => `  '/legacy/js/${s.file}',`).join('\n');
fs.writeFileSync('src/legacy/scripts.ts', `// Generated by tools/split-legacy.mjs. Order matters: later blocks override earlier functions.\nexport const LEGACY_SCRIPTS: string[] = [\n${list}\n];\n`);
console.log(scripts.length, 'scripts,', (css.length / 1024) | 0, 'KB css,', markup.length, 'chars markup');
